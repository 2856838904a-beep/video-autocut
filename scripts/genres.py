def get(name: str) -> dict:
    if name not in PROFILES:
        raise KeyError(f"未知品类 {name!r};可选:{', '.join(PROFILES)}")
    return PROFILES[name]


def list_profiles() -> str:
    lines = []
    for k, v in PROFILES.items():
        mark = "✅已验证" if v.get("verified") else "⚠️ 未验证"
        lines.append(f"  {k:<10} {mark}  {v['label']}")
        lines.append(f"             {v['note']}")
    return "\n".join(lines)


